-- 世界坐标 (x, y) 是不是水：1 = 水，0 = 陆
function ChoukaMaskIsWater(x, y)
    if x == nil or y == nil then
        return 1                         -- 坐标无效：按水处理（宁可不放陆地单位到海里）
    end
    local px = CHOUKA_MASK_PX_A + CHOUKA_MASK_PX_B * x
    local py = CHOUKA_MASK_PY_A + CHOUKA_MASK_PY_B * y
    local gx = floor(px / CHOUKA_MASK_CELL_PX)
    local gy = floor(py / CHOUKA_MASK_CELL_PX)
    if gx < 0 or gy < 0 or gx >= CHOUKA_MASK_GW or gy >= CHOUKA_MASK_GH then
        return 1                         -- 出图 = 地图边角外海
    end
    local row = ChoukaLandSpans[gy + 1]
    if row == nil then
        return 1
    end
    for i = 1, getn(row), 2 do
        if gx >= row[i] and gx <= row[i + 1] then
            return 0                     -- 落在陆地区间里
        end
    end
    return 1
end
